/**
 * 「视频制作模式」 for DSH NEXT. The new host reads agent presets from folders at startup —
 * `<dshHome>/.agent-presets/<id>/preset.yml` (name, description) + `agent.cordis.yml` (the agent's plugin list) —
 * instead of taking ctx.agentPresets.register() calls from plugins. The plugin writes its own folder there
 * (id `video-maker`), only ever touching a folder it generated itself (first line of preset.yml carries
 * GENERATED_MARK): a same-named preset the user made is left alone. Skipped with DSH_VIDEO_SKIP_PRESET_INSTALL=1.
 * Format as in the public DSH preset collections (e.g. github.com/my-dsh-plugin/dsh-presets, MIT).
 */
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { BRAND } from '../shared/brand.js'

export const VIDEO_MAKER_PRESET_ID = 'video-maker'
export const VIDEO_MAKER_PRESET_NAME = '视频制作模式'
export const VIDEO_MAKER_PRESET_DESCRIPTION =
  `${BRAND.productName}：支持素材导入、AI 分镜策划、音效配乐混音、Remotion + Three.js 3D / HTML5 双引擎动效与本地真人配音全链路视频工作台。`
export const GENERATED_MARK = '# generated by dsh-video-workbench'

/** DSH's home folder, the way DSH and the plugin's model discovery find it. */
export function resolveDshHomeDir() {
  return process.env.DSH_CLIENT_HOME || process.env.DSH_HOME || join(homedir(), '.dsh')
}

/** A YAML block scalar (`|-`) body: every line indented, blank lines kept. */
function blockScalar(text, indent) {
  const pad = ' '.repeat(indent)
  return String(text)
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((l) => (l.trim() ? pad + l.replace(/\s+$/, '') : ''))
    .join('\n')
}

/** The two files of the preset folder, as text. */
export function buildVideoMakerPresetFiles({ personaText = '', version = '' } = {}) {
  const head = `${GENERATED_MARK} ${version || ''}`.trim()
  const presetYml = [
    `${head} — delete this folder to remove 「${VIDEO_MAKER_PRESET_NAME}」 from DSH`,
    `name: ${JSON.stringify(VIDEO_MAKER_PRESET_NAME)}`,
    `description: ${JSON.stringify(VIDEO_MAKER_PRESET_DESCRIPTION)}`,
    '',
  ].join('\n')
  const persona = `${String(personaText || '').trim()}\n\n（运行环境：模型 {{model}} · 工作目录 {{cwd}}）`
  const plugin = (id, name, extra = []) => [`- id: ${id}`, `  name: '${name}'`, ...extra].join('\n')
  const cordisYml = [
    `${head}`,
    `# The 「${VIDEO_MAKER_PRESET_NAME}」 agent: the video director persona plus the standard file / shell / jobs / skill tools.`,
    '# The video tools themselves come from the dsh-video-workbench plugin.',
    '',
    plugin('persona', '@deepseek-ai/dsh-persona', ['  config:', '    text: |-', blockScalar(persona, 6)]),
    '',
    plugin('agent-instructions', '@deepseek-ai/dsh-agent-instructions'),
    '',
    plugin('time-context', '@deepseek-ai/dsh-time-context'),
    '',
    plugin('tool-bash', '@deepseek-ai/dsh-tool-bash', ["  disabled: !!js process.platform === 'win32'"]),
    '',
    plugin('tool-pwsh', '@deepseek-ai/dsh-tool-pwsh', ["  disabled: !!js process.platform !== 'win32'"]),
    '',
    plugin('tool-fs', '@deepseek-ai/dsh-tool-fs'),
    '',
    plugin('tool-fs-search', '@deepseek-ai/dsh-tool-fs-search'),
    '',
    plugin('tool-jobs', '@deepseek-ai/dsh-tool-jobs'),
    '',
    plugin('skill-filesystem', '@deepseek-ai/dsh-skill-filesystem'),
    '',
    plugin('tool-skill', '@deepseek-ai/dsh-tool-skill'),
    '',
  ].join('\n')
  return { 'preset.yml': presetYml, 'agent.cordis.yml': cordisYml }
}

/**
 * Write (or refresh) `<dshHome>/.agent-presets/video-maker/`. Returns { ok, action, path, reason }:
 * action 'created' | 'updated' | 'unchanged' | 'kept-user' (a same-named preset not made by this plugin) | 'skipped'.
 */
export function installVideoMakerPresetFolder({ personaText = '', version = '', dshHome = resolveDshHomeDir() } = {}) {
  if (process.env.DSH_VIDEO_SKIP_PRESET_INSTALL === '1') return { ok: false, action: 'skipped', path: '', reason: 'DSH_VIDEO_SKIP_PRESET_INSTALL=1' }
  if (!dshHome || !existsSync(dshHome)) return { ok: false, action: 'skipped', path: '', reason: `DSH 配置目录不存在：${dshHome || '(空)'}` }
  const dir = join(dshHome, '.agent-presets', VIDEO_MAKER_PRESET_ID)
  const files = buildVideoMakerPresetFiles({ personaText, version })
  const presetPath = join(dir, 'preset.yml')
  const existed = existsSync(dir)
  if (existed) {
    const cur = existsSync(presetPath) ? readFileSync(presetPath, 'utf8') : ''
    if (!cur.startsWith(GENERATED_MARK)) {
      return { ok: false, action: 'kept-user', path: dir, reason: '这个文件夹里的同名预设不是本插件生成的，保持原样' }
    }
    const same = Object.entries(files).every(([name, text]) => existsSync(join(dir, name)) && readFileSync(join(dir, name), 'utf8') === text)
    if (same) return { ok: true, action: 'unchanged', path: dir, reason: '' }
  }
  mkdirSync(dir, { recursive: true })
  // agent.cordis.yml first, preset.yml (what DSH looks for) last; each written whole and renamed into place
  for (const name of ['agent.cordis.yml', 'preset.yml']) {
    const tmp = join(dir, `.${name}.${process.pid}.tmp`)
    try {
      writeFileSync(tmp, files[name], 'utf8')
      renameSync(tmp, join(dir, name))
    } finally {
      rmSync(tmp, { force: true })
    }
  }
  return { ok: true, action: existed ? 'updated' : 'created', path: dir, reason: '' }
}
